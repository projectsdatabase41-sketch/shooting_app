'workflow',
$t$Пользователь спрашивает, что за приложение, где что лежит, или вы впервые готовите данные для Puls.$t$,
$t$Puls — приложение для спортивной пулевой стрельбы (Android, Windows, веб). Записывает каждый выстрел КООРДИНАТАМИ пробоины в миллиметрах, а не только очками: из координат считаются очки, средняя точка попадания, кучность и направление увода.
- Роли: спортсмен (ведёт тренировки) и тренер (смотрит дневник спортсмена по выданному им токену, комментирует). Режим переключается в настройках.
- Вкладки спортсмена: Упражнения · Мишень · Статистика · Ассистент · Настройки, плюс собственные плитки «Сервисы». Тренера: Дневник · Спортсмены · Статистика · Ассистент · Настройки. Состав вкладок пользователь настраивает сам (кроме «Мишени» и «Настроек» — их скрыть нельзя).
- Приложение стартует пустым: ни демо-упражнений, ни демо-тренировок.
- Мишени (код → что это): rifle_10m — № 8, пневм. винтовка 10 м, калибр 4.5; pistol_10m — № 9, пневм. пистолет 10 м, 4.5; rifle_50m — № 7, м/к винтовка 50 м, 5.6; pistol_25m — № 4, пистолет 25 м, 5.6. Других кодов приложение не знает.
- Приложение не оценивает «хорошо/плохо» и не мешает стрелять: все выстрелы записываются всегда.$t$,
array['puls','обзор','структура']
where not exists (select 1 from qwen_public_instructions where topic = $t$Puls: что это и как устроено$t$);

