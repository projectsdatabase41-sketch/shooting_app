- Писать в таблицы тренировок может только владелец базы (вход по почте и паролю → токен). Публичный ключ позволяет только читать инструкции. Ключ service_role никогда не запрашивайте и не используйте.
- Порядок из-за внешних ключей: target_faces (найти по code) → exercise_templates (искать по названию + мишени, не плодить) → training_packages (package_status = 'completed' — только такие приложение считает завершёнными) → exercises (ровно одна строка на тренировку, её id РАВЕН id пакета, иначе приложение не найдёт выстрелы) → shots (exercise_id = id пакета; final_score — результат как есть; shot_time_ms — целое смещение от начала в миллисекундах или пусто).
- Разрешённые значения source/coordinate_source у выстрела: pdf, photo, file_import (плюс manual, auto, manual_corrected, tap, score_angle по смыслу); имя прибора туда не пишется — в extra.
- Идентификаторы детерминированные, вставка «игнорировать дубликаты»: повторный прогон не должен плодить строки.
- Актуальная структура таблиц и правила лежат в самой базе пользователя: таблица table_docs (читается публичным ключом).
- После записи прочитайте данные обратно и покажите пользователю сводку (мишень, дата, число выстрелов, суммы) — пусть сверит в приложении.$t$,
array['puls','запись','база','supabase']
