5. Пристрелка: counts=false на самих выстрелах.
6. Показатели прибора (время прицеливания, устойчивость, скорость) — в extra выстрела структурой под ключом с именем прибора: {"scatt": {"aim_time_s": 18.4}}. Не в текст комментария.
7. Проверки до выдачи файла: число выстрелов совпало с заявленным; сумма по каждой серии и общая совпала с итогом в источнике; номера выстрелов без дыр; результаты в 0…10.9. Не сошлось — не выдавайте файл молча, покажите расхождение пользователю.
8. Не уверены — спросите. Пропущенное поле лучше пустым, чем выдуманным. Не подгоняйте цифры под сумму.
9. Заполняйте source — откуда взяты данные (для разбора спорных случаев).$t$,
array['puls','правила','импорт','координаты']
