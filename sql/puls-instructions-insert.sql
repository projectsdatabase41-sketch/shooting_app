3. Откуда брать координаты (лестница точности): (A) настоящие координаты из источника (векторные пробоины в PDF, CSV прибора) — берите как есть; (B) есть результат и направление — радиус считайте из результата, угол берите с картинки (формула: https://github.com/projectsdatabase41-sketch/shooting_app/blob/main/DATA-INGEST.md, раздел 6); (C) только результаты — x_mm/y_mm обязаны быть числами: поставьте 0, в extra выстрела {"coords":"unknown"} и СКАЖИТЕ пользователю, что точки на мишени условные. Не выдумывайте положение.
