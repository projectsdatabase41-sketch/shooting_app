/// не «наугад», а по разряду из профиля спортсмена (`UserProfile.rankOf`)
/// и нормативной таблице ниже.
///
/// ВАЖНО: значения — ОРИЕНТИРОВОЧНЫЕ средние одного выстрела (в очках,
