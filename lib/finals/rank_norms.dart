/// Нормативные средние и разбросы ботов финалов по разряду спортсмена.
class RankNorms {
  RankNorms._();

  /// Код myшени → строка [kBotRankNorms] по ВИДУ оружия: финал 3P стреляет
  /// по мишени `rifle_50m`, но норматив у него на всю сумму трёх положений
  /// (МВ-3×40). Кроме кодов мишеней принимаются и предметы ЕВСК
  /// («ВП-60», «ПП-40», «МВ-3×20»…) — из [kEwsk2026]: предметы винтовки
  /// с десятыми/в целых считаются одним упражнением, т.е. «ВП-60 /
  /// ВП-60 (целые)» дают одну и ту же таблицу бота.
  static String resolveKey(String codeOrExercise) {
    final q = codeOrExercise.trim();
    switch (q) {
      case 'rifle_10m':
      case 'ВП-60':
      case 'ВП-60 (целые)':
      case 'ВП-40':
      case 'ВП-30 лёжа':
      case 'ВП-20 с упора':
        return 'rifle_10m';
      case 'pistol_10m':
      case 'ПП-60':
      case 'ПП-40':
      case 'ПП-30':
      case 'ПП-20 с упора':
        return 'pistol_10m';
      case 'rifle_50m':
      case 'rifle_50m_3p':
      case 'МВ-60 (десятые)':
      case 'МВ-60 (целые)':
      case 'МВ-3×20':
      case 'МВ-3×40':
        // МВ-60 (лёжа) и МВ-3×20 для бота сводятся к таблице 3P: отдельной
        // prone-таблицы бота нет, ближайшее по виду оружия упражнение.
        return 'rifle_50m_3p';
    }
    return q;
  }

  /// Строка таблицы для кода мишени (или предмета ЕВСК) [codeOrExercise] и
  /// разряда [rankId].
  ///
  /// Пустой разряд и «Нет разряда» считаем как 3-й взрослый (средний новичок
  /// клуба); ЗМС — на уровне МСМК. Неизвестный код — ближайшая таблица по
  /// виду оружия: пистолет → таблица пистолета, остальное → винтовка 10 м.
  static (double, double) _entry(String codeOrExercise, String rankId) {
    final key = resolveKey(codeOrExercise);
    final q = codeOrExercise.trim();
    final table = kBotRankNorms[key] ??
        (q.startsWith('pistol') || q.startsWith('ПП')
            ? kBotRankNorms['pistol_10m']!
            : kBotRankNorms['rifle_10m']!);
    final rank = switch (rankId.trim()) {
      '' || 'Нет разряда' => '3 взрослый',
      'ЗМС' => 'МСМК',
      final r => r,
    };
    return table[rank] ?? table['3 взрослый']!;
  }

  /// Средний ожидаемый результат выстрела (очки с десятыми) для кода мишени
  /// (или предмета ЕВСК, см. [resolveKey]) и разряда [rankId].
  ///
  /// Все средние — из сумм ЕВСК 2026–2029 (приказ № 201, прил. 22), кроме
  /// явно помеченных «оценка, не из ЕВСК» строк юношеских/III разрядов.
  /// Юношеские разряды маппируются на соответствующие возрастные упражнения
  /// (комментарии у строк [kBotRankNorms]).
  static double averageFor(String codeOrExercise, String rankId) =>
      _entry(codeOrExercise, rankId).$1;

  /// Ожидаемый разброс одного выстрела (σ, очки) для той же пары.
  static double spreadFor(String codeOrExercise, String rankId) =>
      _entry(codeOrExercise, rankId).$2;

  /// Нормативная сумма ЕВСК упражнения [exerciseKey] для разряда в
  /// обозначениях ЕВСК, либо null — разряда в упражнении нет.
  static double? ewskSumFor(String exerciseKey, String rankId) =>
      kEwsk2026[exerciseKey]?.sums[rankId.trim()];
}
