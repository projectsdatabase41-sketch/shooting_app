/// Нормативные средние и разбросы ботов финалов по разряду спортсмена.
class RankNorms {
  RankNorms._();

  /// Ключ таблицы по коду мишени: финал 3P стреляет по мишени `rifle_50m`,
  /// но норматив у него один — на всю сумму трёх положений.
  static String _faceKey(String faceCode) => switch (faceCode) {
        'rifle_50m' => 'rifle_50m_3p',
        _ => faceCode,
      };

  /// Строка таблицы для мишени [faceCode] и разряда [rankId].
  ///
  /// Пустой разряд и «Нет разряда» считаем как 3-й взрослый (средний новичок
  /// клуба); ЗМС — на уровне МСМК. Неизвестная мишень — ближайшая по виду:
  /// пистолет → таблица пистолета, остальное → пневматическая винтовка.
  static (double, double) _entry(String faceCode, String rankId) {
    final key = _faceKey(faceCode);
    final table = kBotRankNorms[key] ??
        (faceCode.startsWith('pistol') ? kBotRankNorms['pistol_10m']! : kBotRankNorms['rifle_10m']!);
    final rank = switch (rankId.trim()) {
      '' || 'Нет разряда' => '3 взрослый',
      'ЗМС' => 'МСМК',
      final r => r,
    };
    return table[rank] ?? table['3 взрослый']!;
  }

  /// Средний ожидаемый результат выстрела (очки с десятыми) для мишени
  /// [faceCode] и разряда [rankId].
  static double averageFor(String faceCode, String rankId) => _entry(faceCode, rankId).$1;

  /// Ожидаемый разброс одного выстрела (σ, очки) для той же пары.
  static double spreadFor(String faceCode, String rankId) => _entry(faceCode, rankId).$2;
}
