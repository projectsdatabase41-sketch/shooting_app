/// Открытие базы — своё для нативных платформ и своё для браузера.
///
/// Разделение сделано УСЛОВНЫМ ЭКСПОРТОМ, а не проверкой `kIsWeb` в
/// одном файле, и это принципиально: `package:sqlite3/sqlite3.dart`
/// тянет за собой `dart:ffi`, которого в браузере нет вовсе. Проверка
/// во время выполнения тут не спасает — сборка под web упала бы ещё на
/// этапе компиляции, до всякого `if`. Условный экспорт решает вопрос
/// раньше: в web-сборку файл с ffi просто не попадает.
///
/// Обе реализации возвращают `CommonDatabase` — общий интерфейс пакета
/// `sqlite3`. Благодаря ему весь остальной код (а он весь ходит через
/// `db.select` / `db.execute` с обычным SQL) не знает и не должен знать,
/// где именно лежит база: в файле на диске или в IndexedDB браузера.
export 'db_opener_io.dart' if (dart.library.js_interop) 'db_opener_web.dart';
