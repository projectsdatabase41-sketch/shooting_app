/// Алгоритм подсчёта очков.
///
/// Версия от 2026-09-02, по ТЗ пользователя «Техническое задание для
/// алгоритма расчета очков (ISSF Мишень №7, 50м)». Заменяет прежнюю
/// модель «вложенных колец внутри пробоины» — см. раздел «Что изменилось
/// и почему» ниже.
///
/// ## Алгоритм
///
/// 1. **Радиальное отклонение.** `R_center = √(x² + y²)` — расстояние от
///    центра мишени до ЦЕНТРА пробоины, мм.
/// 2. **Учёт калибра (inward gauging, измерение «вовнутрь»).** Достоинство
///    выстрела определяется по краю пробоины, ближайшему к центру:
///    `R_calc = R_center − радиус_пули`.
///    `R_calc` МОЖЕТ БЫТЬ ОТРИЦАТЕЛЬНЫМ и обрезать его по нулю нельзя —
///    именно отрицательная зона даёт десятые доли внутри десятки (см.
///    ниже про 10.9).
/// 3. **Целая часть.** Номер самого внутреннего кольца, чью границу
///    зацепил край пробоины: наименьшее `i`, при котором
///    `R_calc ≤ ringRadiiMm[i]`; габарит = `10 − i`. Границы — официальные
///    (`TargetFace.ringDiametersMm`), не вычисленные.
/// 4. **Десятая доля.** Шаг одной десятой = ширина кольца / 10
///    (`TargetFace.decimalStepMm`). Отсчёт идёт ВНУТРЬ от границы
///    найденного кольца:
///    `k = floor((граница_кольца − R_calc) / шаг)`, ограничение `0..9`;
///    результат = `габарит + k/10`.
///
/// Граница принадлежит БОЛЕЕ ВЫСОКОМУ достоинству (край пробоины ровно
/// на линии десятки — это 10.0, а не 9.9), как и в правилах.
///
/// ## Сверка с контрольной таблицей ТЗ (мишень № 7, калибр 5.6)
///
/// Кольцо 10 = 5.2 мм, кольцо 9 = 13.2 мм, ширина кольца 8.0 мм,
/// шаг десятой 0.8 мм, радиус пули 2.8 мм. Расстояния — от центра
/// мишени до центра пробоины:
///
/// | R_center | 0.8  | 1.6  | 2.4  | 3.2  | 4.0  | 4.8  | 5.6  | 6.4  | 7.2  | 8.0  | 16.0 |
/// |----------|------|------|------|------|------|------|------|------|------|------|------|
/// | Результат| 10.9 | 10.8 | 10.7 | 10.6 | 10.5 | 10.4 | 10.3 | 10.2 | 10.1 | 10.0 | 9.0  |
///
/// Совпадает с таблицей ветвления из ТЗ полностью (проверено тестами в
/// `test/scoring_test.dart`).
///
/// ## Два уточнения к тексту ТЗ
///
/// 1. **Пороги таблицы ветвления — это `R_center`, а не `R_calc`.**
///    В тексте ТЗ они подписаны как `R_calc` (уже с вычтенным радиусом
///    пули), но сами числа говорят об обратном: 10.0 стоит на 8.0 мм, а
///    это ровно `5.2 + 2.8` — официальная граница десятки ПЛЮС радиус
///    пули; 9.0 стоит на 16.0 мм = `13.2 + 2.8`. То есть вычет калибра в
///    этих порогах уже учтён. Если понимать их буквально как `R_calc`,
///    радиус пули вычитался бы дважды, десятка растянулась бы до 10.8 мм
///    от центра, и та же таблица дала бы на своих же порогах 10.5 вместо
///    10.9 и 9.6 вместо 10.0. Реализована таблица, а не подпись.
/// 2. **Замкнутая формула `10.9 − trunc(R_calc/0.8, 1)` из ТЗ
///    противоречит таблице ветвления и не используется.** Она делит на
///    шаг 0.8 и тут же отсекает результат до одного знака, из-за чего
///    падает в десять раз быстрее нужного: при `R_calc = 1.0` даёт 9.7,
///    тогда как таблица в той же точке даёт 10.8, а при `R_calc = 8.0` —
///    0.9 вместо 10.0. Делить нужно было на ширину кольца (8.0), а не на
///    шаг десятой. Источником истины взята таблица ветвления — она
///    помечена в ТЗ как «готовая логика ветвления» и, в отличие от
///    формулы, согласуется с официальной геометрией мишени.
///
/// ## Что изменилось и почему (важно)
///
/// Прежняя модель считала десятую долю от РАДИУСА ПУЛИ: пробоина
/// мысленно делилась на 10 вложенных колец, и весь диапазон .0–.9
/// укладывался в радиус пробоины. Новая модель считает её от ШИРИНЫ
/// КОЛЬЦА МИШЕНИ — как и положено, десятая доля это одна десятая
/// кольца.
///
/// Для мишени № 8 (винтовка 10 м) обе модели совпадали по чистой
/// случайности: там `9 × шаг = 9 × 0.25 = 2.25 мм`, и это ровно радиус
/// пули. На остальных трёх мишенях старая модель ошибалась, причём
/// сильно. Пример на № 7: выстрел с центром в 4.0 мм от центра мишени
/// старая модель оценивала как **10.9**, новая даёт **10.5**. Старая
/// выдавала 10.9 всему, что легло ближе 5.2 мм, — то есть внутренняя
/// десятка была неоправданно щедрой.
///
/// Ничего в алгоритме не зашито под конкретную мишень: калибр, границы
/// колец, шаг десятой (`TargetFace.decimalStepMm`) и метод измерения
/// (`TargetFace.gaugingOffsetMm`) берутся из справочника мишеней. Шаги
/// у четырёх мишеней разные: № 8 — 0.25 мм, № 9 и № 7 — 0.8 мм,
/// № 4 — 2.5 мм.
///
/// ## Про «наружу» для пистолетных мишеней
///
/// Метод измерения — параметр мишени (`TargetFace.gauging`), алгоритм
/// умеет оба. У всех четырёх стоит «вовнутрь»; почему — подробно
/// разобрано в комментарии к полю `TargetFace.gauging`. Коротко:
/// деление inward/outward в правилах ISSF идёт по размеру кольца, а не
/// по дисциплине, относится к измерению бумаги калибромером (целые
/// очки), а при сложении радиуса пули результат для пневматического
/// пистолета упирается в 10.4 — 10.9 становится недостижимой.
double scoreFor(Shot shot, TargetFace face) {
  return scoreForRadius(shot.radiusMm, face);
}

/// Результат по РАССТОЯНИЮ от центра мишени до центра пробоины (мм) —
/// это `R_center` из ТЗ, шаги 1–2 делаются внутри.
///
/// Знак поправки на калибр берётся из самой мишени
/// (`TargetFace.gaugingOffsetMm`): «вовнутрь» — минус радиус пули,
/// «наружу» — плюс. Ни знак, ни величина в алгоритме не зашиты.
double scoreForRadius(double distanceMm, TargetFace face) {
  return scoreForEffectiveRadius(distanceMm + face.gaugingOffsetMm, face);
}

/// Результат по уже готовому `R_calc` (расстояние минус радиус пули).
///
/// Отрицательный `R_calc` — нормальная и осмысленная ситуация: пробоина
/// накрыла центр мишени. Обрезать его по нулю НЕЛЬЗЯ, иначе пропадут
/// все десятые внутри десятки (на № 7 значения 10.1–10.9 лежат как раз
/// в диапазоне `R_calc` от −2.0 до 4.4).
double scoreForEffectiveRadius(double effectiveRadius, TargetFace face) {
  final radii = face.ringRadiiMm;
  final step = face.decimalStepMm;
  if (radii.isEmpty || step <= 0) return 0.0;

  for (var i = 0; i < radii.length; i++) {
    // Допуск 1e-9: граница принадлежит более высокому габариту, а
    // двоичная арифметика на «круглых» миллиметрах даёт хвосты
    // (8.0 − 2.8 = 5.200000000000000178…).
    if (effectiveRadius <= radii[i] + 1e-9) {
      final ring = 10 - i;
      // Границы без clamp() намеренно: `int.clamp()` статически возвращает
      // `num`, и выражение `ring + k / 10` тогда рискует получить тип
      // `num` вместо `double`. Явные проверки оставляют k строго `int`.
      var k = ((radii[i] - effectiveRadius) / step + 1e-9).floor();
      if (k < 0) k = 0;
      if (k > 9) k = 9;
      return ring + k / 10;
    }
  }
  return 0.0;
}

/// Обратная задача: на каком расстоянии от центра мишени должен лежать
/// центр пробоины, чтобы результат был ровно `ring.decimal`.
///
/// Нужна слайдеру подбора десятых на экране правки (A.6): пользователь
/// выбирает десятую долю, а пробоина сдвигается по своему лучу на
/// соответствующий радиус, не меняя угла.
///
/// Возвращается СЕРЕДИНА полосы этой десятой, а не её граница — на
/// границе двоичная арифметика может отправить результат в соседнее
/// значение, а из середины полосы `scoreForRadius` гарантированно
/// возвращает ровно то, что просили (проверено round-trip тестом на
/// всех 400 сочетаниях мишень × габарит × десятая).
double radiusForScore(int ring, int decimal, TargetFace face) {
  final radii = face.ringRadiiMm;
  final index = 10 - ring;
  if (index < 0 || index >= radii.length) return 0.0;
  final step = face.decimalStepMm;
  final rCalc = radii[index] - (decimal + 0.5) * step;
  final distance = rCalc - face.gaugingOffsetMm;
  return distance < 0 ? 0.0 : distance;
}

/// Мнемоника "часы" (1..12, по часовой стрелке, 12 — вверх) — часть B.4/A.6
/// logic-personalization-spec.md.
int clockDirection(Shot shot) {
  final deg = shot.angleDeg; // 0 = 12 часов
  final hour = (deg / 30).round() % 12;
  return hour == 0 ? 12 : hour;
}
